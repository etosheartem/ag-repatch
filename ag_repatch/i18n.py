_language = "ru"


def set_language(locale_name: str) -> None:
    global _language
    code = locale_name.lower().replace("-", "_").split("_")[0].split(".")[0]
    _language = "ru" if code == "ru" else "en"


def language() -> str:
    return _language


def tr(source: str) -> str:
    return source if _language == "ru" else ENGLISH.get(source, source)


